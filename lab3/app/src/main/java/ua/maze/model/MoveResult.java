package ua.maze.model;

/** Чим закінчилася спроба зробити хід. */
public enum MoveResult {
    /** Гравець перейшов на сусідню клітинку. */
    MOVED,
    /** Там стіна або край поля — гравець лишився на місці. */
    BLOCKED,
    /** Гравець дійшов до виходу — перемога. */
    ESCAPED,
    /** Гра вже закінчена, ходи не приймаються. */
    FINISHED
}
